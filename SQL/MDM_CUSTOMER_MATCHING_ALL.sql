USE DATABASE MDM_CUSTOMER_MATCHING;
USE SCHEMA PUBLIC;  -- @Snowflake Docs

-- -----------------------------------------------------------------------------
-- Sequence and UDF for CUSTOMER_BUSINESS_ID
-- -----------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS CUSTOMER_BUSINESS_ID_SEQ
  START = 1
  INCREMENT = 1
  COMMENT = 'Sequence to generate the numeric component for CUSTOMER_BUSINESS_ID';

CREATE OR REPLACE FUNCTION GENERATE_CUSTOMER_BUSINESS_ID(SEQ_VALUE NUMBER)
RETURNS VARCHAR
LANGUAGE SQL
COMMENT = 'Generates ID as CUS + 9-digit zero-padded number + Base36 check char.'
AS
$$
  'CUS'
  || LPAD(TO_VARCHAR(SEQ_VALUE), 9, '0')
  || IFF(MOD(SEQ_VALUE, 36) < 10,
         TO_VARCHAR(MOD(SEQ_VALUE, 36)),
         CHR(55 + MOD(SEQ_VALUE, 36))
     )
$$;

-- -----------------------------------------------------------------------------
-- Tables (with related post-creation updates grouped directly after each CREATE)
-- -----------------------------------------------------------------------------
-- CUSTOMER_ADDRESS (CTAS merges population + full detail + embedding)
CREATE OR REPLACE TABLE MDM_CUSTOMER_MATCHING.PUBLIC.CUSTOMER_ADDRESS AS
SELECT
  GENERATE_CUSTOMER_BUSINESS_ID(CUSTOMER_BUSINESS_ID_SEQ.NEXTVAL) AS CUSTOMER_BUSINESS_ID,
  v.NAME AS CUSTOMER_NAME,
  v.ADDRESS_LINE_1,
  v.ADDRESS_LINE_2,
  v.CITY,
  NULL AS COUNTY,
  v.STATE,
  v.POSTAL_CODE,
  NULL AS POSTALCODE_EXTENSION,
  v.COUNTRY,
  NULL AS PHONE,
  RTRIM(
    ARRAY_TO_STRING(
      ARRAY_CONSTRUCT_COMPACT(
        IFF(TRIM(v.NAME) = '', NULL, TRIM(v.NAME)),
        IFF(TRIM(v.ADDRESS_LINE_1) = '', NULL, TRIM(v.ADDRESS_LINE_1)),
        IFF(TRIM(v.ADDRESS_LINE_2) = '', NULL, TRIM(v.ADDRESS_LINE_2)),
        IFF(TRIM(v.CITY) = '', NULL, TRIM(v.CITY)),
        IFF(TRIM(v.STATE) = '', NULL, TRIM(v.STATE)),
        IFF(TRIM(v.POSTAL_CODE) = '', NULL, TRIM(v.POSTAL_CODE))
      ),
      ', '
    )
  ) AS CUSTOMER_FULL_DETAIL,
  AI_EMBED('snowflake-arctic-embed-m', customer_full_detail) AS CUSTOMER_FULL_DETAIL_EMBEDDING
FROM VALID_CUSTOMERS v;

-- CUSTOMER_IDENTIFIER (schema only; populated by tools/processes)
CREATE TABLE IF NOT EXISTS MDM_CUSTOMER_MATCHING.PUBLIC.CUSTOMER_IDENTIFIER (
